r"""Copy data/backtest/<tour>/frozen.json into the tracked Backtest/FrozenParams.py (so PredictDay is reproducible from git).

Usage: .venv\Scripts\python.exe -m Backtest.WriteFrozenParams --version tennis_blend_v1_2026-11-13
"""
import argparse
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]


def Main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--version", required=True)
    args = parser.parse_args(argv)
    lines = ['"""Frozen model parameters, generated by Backtest.WriteFrozenParams from data/backtest/<tour>/frozen.json.',
             'Do not edit by hand: re-run Backtest.RunBacktest (tune + validation only), then regenerate."""', "",
             f"MODEL_VERSION = {args.version!r}", "", "FROZEN = {"]
    for tour in ("atp", "wta"):
        frozen = json.loads((REPO_ROOT / "data" / "backtest" / tour / "frozen.json").read_text())
        lines.append(f"    {tour!r}: {{'elo': {frozen['elo']!r}, 'sr': {frozen['sr']!r}, "
                     f"'blend_weight_sr': {frozen['blend_weight_sr']!r}, 'frozen_at': {frozen['frozen_at']!r}}},")
    lines.append("}")
    (REPO_ROOT / "Backtest" / "FrozenParams.py").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    Main()